#!/usr/bin/env python3
"""
backfill_metabev_products.py — enrich drinks rows for MetaBev from their
Shopify product feed (the source of their inventory import).

For each approved MetaBev drink with missing data, fills:
  - buy_url:     the product page on www.meta-bev.com
  - description: distiller/brand copy from the Shopify body_html (stripped)
  - abv:         parsed from the product title/body (e.g. "40% ABV")
  - origin:      country from the product's vendor/type heuristics

Run from the repo root:
    python3 scripts/backfill_metabev_products.py > supabase/migrations/061_backfill_metabev_products.sql
"""
import json, re, html, sys, urllib.request

SITE = 'https://www.meta-bev.com'
SUPPLIER = 'MetaBev'

def fetch_products():
    products = []
    page = 1
    while True:
        url = f'{SITE}/products.json?limit=250&page={page}'
        with urllib.request.urlopen(url, timeout=30) as r:
            data = json.load(r)
        prods = data.get('products', [])
        if not prods: break
        products.extend(prods)
        if len(prods) < 250: break
        page += 1
    return products

def strip_html(s):
    s = re.sub(r'<br\s*/?>', ' ', s or '')
    s = re.sub(r'<[^>]+>', ' ', s)
    s = html.unescape(s)
    return re.sub(r'\s+', ' ', s).strip()

def norm(t):
    t = t.lower()
    t = re.sub(r'\d+[\.,]?\d*\s*%?\s*abv', '', t)
    t = re.sub(r'\d+\s*ml\b', '', t)
    t = re.sub(r'\(\s*[^)]*x\s*\d+\s*(bottles?|cans?)?s?\s*\)', '', t)
    t = re.sub(r'x\s*\d+', '', t)
    t = re.sub(r'[^a-z0-9 ]', ' ', t)
    return re.sub(r'\s+', ' ', t).strip()

def score_match(cat_name, prod_title):
    cn, pn = norm(cat_name), norm(prod_title)
    cw, pw = set(cn.split()), set(pn.split())
    if not cw: return 0
    inter = cw & pw
    return len(inter) / max(len(cw), 1) + (2 if cn == pn else 0)

def extract_abv(title, body):
    # Prefer patterns like "ABV 51.4%", "Alcohol%: 40%", "40.0% ABV"
    for src in (title, (body or '')[:600]):
        for pat in (r'ABV\s*(\d{1,2}(?:\.\d)?)\s*%',
                    r'[Aa]lcohol\s*%?\s*:?\s*(\d{1,2}(?:\.\d)?)\s*%',
                    r'(\d{1,2}(?:\.\d)?)\s*%\s*ABV'):
            m = re.search(pat, src)
            if m and 0.5 <= float(m.group(1)) <= 95:
                return f'{m.group(1)}%'
    return None

def clean_description(body):
    # Strip trailing boilerplate the site already surfaces as separate fields.
    if not body: return None
    body = re.sub(r'\s*Alcohol\s*%?\s*:?\s*\d{1,2}(?:\.\d)?\s*%.{0,60}$', '', body)
    body = re.sub(r'\s*ABV\s*\d{1,2}(?:\.\d)?\s*%.{0,60}$', '', body)
    if len(body) > 400:
        body = body[:400].rsplit(' ', 1)[0] + '…'
    return body or None

ORIGIN_HINTS = [
    (r'tequila|mezcal', 'Mexico'),
    (r'scotch|islay|speyside|highland|glen\s', 'Scotland'),
    (r'irish whiskey|bushmills|black bush', 'Ireland'),
    (r'bourbon|tennessee|jack daniel|woodford', 'USA'),
    (r'nikka|yoichi|japanese|tokki|orion|estrella', None),  # handled by vendor below
    (r'cognac|frapin|vecchia romagna|pommery|brut royal', None),
]
VENDOR_ORIGIN = {
    'Nikka': 'Japan', 'Tokki': 'Korea', 'Orion': 'Japan', 'Estrella Damm': 'Spain',
    'Pommery': 'France', 'Frapin': 'France', 'Vecchia Romagna': 'Italy',
    'Perrier': 'France', 'Fever-Tree': 'United Kingdom', 'Flor de Cana': 'Nicaragua',
    'The Kraken': 'Trinidad & Tobago', 'Tito\'s': 'USA', 'The Glendronach': 'Scotland',
    'Glen Grant': 'Scotland', 'Stauning': 'Denmark', 'Scapegrace': 'New Zealand',
    'Woodford Reserve': 'USA', 'Jack Daniel\'s': 'USA', 'Wild Turkey': 'USA',
    'Fernet Branca': 'Italy', 'Bushmills': 'Ireland', '1800 Tequila': 'Mexico',
    'Creyente': 'Mexico', 'Montelobos': 'Mexico', '400 Conejos': 'Mexico',
}

def origin_for(p):
    vendor = (p.get('vendor') or '').strip()
    if vendor in VENDOR_ORIGIN:
        return VENDOR_ORIGIN[vendor]
    text = f"{p['title']} {p.get('product_type') or ''}"
    for pat, origin in ORIGIN_HINTS:
        if origin and re.search(pat, text, re.I):
            return origin
    return None

def esc_sql(s):
    return str(s or '').replace("'", "''")

def main():
    products = fetch_products()
    # Catalogue names come from stdin (one per line) — the approved MetaBev rows.
    catalogue = [l.strip() for l in sys.stdin if l.strip()]
    print('-- 061_backfill_metabev_products.sql')
    print('-- Enrich MetaBev drink rows from their Shopify product feed:')
    print('-- buy_url (product page), description (brand copy), abv, origin.')
    print('-- Generated by scripts/backfill_metabev_products.py — DO NOT hand-edit.')
    print()
    matched = 0
    for cat_name in catalogue:
        best, best_score = None, 0
        for p in products:
            s = score_match(cat_name, p['title'])
            # Never match a bundle/kit product to a single bottle.
            if re.search(r'\bkit\b|\+\s|copy\b', p['title'], re.I):
                s -= 1.5
            if s > best_score:
                best, best_score = p, s
        if not best or best_score < 0.5:
            print(f'-- NO MATCH: {cat_name}')
            continue
        matched += 1
        body = strip_html(best.get('body_html'))
        desc = clean_description(body)
        abv = extract_abv(best['title'], body)
        origin = origin_for(best)
        buy_url = f"{SITE}/products/{best['handle']}"
        sets = []
        if desc: sets.append(f"description = '{esc_sql(desc)}'")
        if abv: sets.append(f"abv = '{esc_sql(abv)}'")
        if origin: sets.append(f"origin = '{esc_sql(origin)}'")
        sets.append(f"buy_url = '{esc_sql(buy_url)}'")
        print(f"-- {cat_name}  <-  {best['title']}")
        print(f"UPDATE drinks SET {', '.join(sets)}")
        print(f"WHERE supplier_name = '{SUPPLIER}' AND name = '{esc_sql(cat_name)}';")
        print()
    print(f'-- matched {matched}/{len(catalogue)}', file=sys.stderr)

if __name__ == '__main__':
    main()
