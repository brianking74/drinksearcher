#!/usr/bin/env python3
"""
extract_hkdrinks_products.py — build a backfill migration for the HK Drinks
catalogue rows (Cincoro + Clase Azul) from the brand pages of the owner's own
shop site (~/cincoro-hk → hkdrinks.shop).

This is the "supplier has no ecommerce feed" case: the facts come from the
supplier's own product pages instead of a Shopify products.json.

Usage:
    python3 scripts/extract_hkdrinks_products.py <path-to-cincoro-hk-repo> > supabase/migrations/063_backfill_hk_drinks.sql

Data taken per product: description (their own copy, trimmed to ~48 words),
ABV (from the tasting-notes block — used as a cross-check), origin (Mexico),
and a buy_url deep link to the product block on their brand page.
"""
import re, html, sys, os, json

MAX_WORDS = 48
SITE = 'https://hkdrinks.shop'
PAGES = [('cincoro.html', 'Cincoro'), ('clase-azul.html', 'Clase Azul')]

# The shop's own catalogue names -> the product block on the brand page.
CATALOGUE_MAP = {
    'Cincoro Collection':          ('cincoro.html', 'cincoro', {'collection': True}),
    'Cincoro Blanco Tequila':      ('cincoro.html', 'cincoro-plata'),
    'Cincoro Reposado Tequila':    ('cincoro.html', 'cincoro-reposado'),
    'Cincoro Gold Tequila':        ('cincoro.html', 'cincoro-gold'),
    'Cincoro Anejo Tequila':       ('cincoro.html', 'cincoro-anejo'),
    'Cincoro Extra Anejo Tequila': ('cincoro.html', 'cincoro-ultra'),
    'Clase Azul Plata':            ('clase-azul.html', 'clase-azul-plata'),
    'Clase Azul Reposado':         ('clase-azul.html', 'clase-azul-reposado'),
    'Clase Azul Gold':             ('clase-azul.html', 'clase-azul-gold'),
    'Clase Azul Anejo':            ('clase-azul.html', 'clase-azul-anejo'),
}

def text(s):
    return re.sub(r'\s+', ' ', html.unescape(re.sub(r'<[^>]+>', ' ', s))).strip()

def trim_words(t, n=MAX_WORDS):
    words = t.split()
    if len(words) <= n: return t.strip()
    clipped = ' '.join(words[:n])
    ends = list(re.finditer(r'[.!?](?=\s|$)', clipped))
    if ends and ends[-1].end() > len(clipped) * 0.5:
        return clipped[:ends[-1].end()].strip()
    return clipped.rsplit(' ', 1)[0].rstrip(',;:') + '…'

def parse_page(path):
    src = open(path, encoding='utf-8').read()
    ids = [(m.start(), m.group(1)) for m in re.finditer(r'<div class="expression-card[^"]*"\s+id="([^"]+)"', src)]
    out = {}
    for idx, (pos, anchor) in enumerate(ids):
        end = ids[idx + 1][0] if idx + 1 < len(ids) else len(src)
        block = src[pos:end]
        name  = re.search(r'expression-card__name">([^<]+)<', block)
        desc  = re.search(r'expression-card__desc">([^<]+)<', block)
        abv   = re.search(r'<span>ABV</span>\s*([\d.]+%)', block)
        if not name: continue
        out[anchor] = {
            'name': name.group(1).strip(),
            'desc': text(desc.group(1)) if desc else '',
            'abv': abv.group(1) if abv else '',
        }
    return out

def esc(s):
    return str(s or '').replace("'", "''")

def main():
    repo = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/cincoro-hk')
    pages = {f: parse_page(os.path.join(repo, f)) for f, _ in PAGES}

    print('-- 063_backfill_hk_drinks.sql')
    print('--')
    print('-- HK Drinks (Cincoro / Clase Azul) rows enriched from the supplier\'s OWN')
    print('-- product pages at hkdrinks.shop — the "no ecommerce feed" case. Data is')
    print('-- their own listing copy + ABV; origin Mexico is the documented source of')
    print('-- both brands (Jalisco). Descriptions capped at ~48 words.')
    print('-- Generated by scripts/extract_hkdrinks_products.py — DO NOT hand-edit.')
    print('--')
    print('-- NOTE for review: the Clase Azul page copy appears templated from the')
    print('-- Cincoro page (differs only by brand name), and its Plata blurb calls the')
    print('-- bottle a "cristalino expression", which is not accurate for a Plata.')
    print('-- Imported as supplied, but worth correcting on hkdrinks.shop.')
    print()
    emitted = 0
    for cat_name, entry in CATALOGUE_MAP.items():
        page, anchor = entry[0], entry[1]
        is_collection = len(entry) > 2 and isinstance(entry[2], dict) and entry[2].get('collection')
        prod = pages.get(page, {}).get(anchor)
        buy = f'{SITE}/{page[:-5]}#{anchor}' if not is_collection else f'{SITE}/{page[:-5]}'
        if not prod and not is_collection:
            print(f"-- NO MATCH: {cat_name} (anchor {anchor} not found in {page})")
            continue
        sets = []
        if prod and prod['desc']:
            sets.append(f"description = '{esc(trim_words(prod['desc']))}'")
        if prod and prod['abv']:
            sets.append(f"abv = '{esc(prod['abv'])}'")
        sets.append("origin = 'Mexico'")
        sets.append(f"buy_url = '{esc(buy)}'")
        label = prod['name'] if prod else 'brand collection page'
        print(f"-- {cat_name}  <-  {label} ({page}#{anchor})")
        print(f"UPDATE drinks SET {', '.join(sets)}")
        print(f"WHERE supplier_name = 'HK Drinks' AND name = '{esc(cat_name)}';")
        print()
        emitted += 1
    print(f'-- emitted {emitted} statements', file=sys.stderr)

if __name__ == '__main__':
    main()
